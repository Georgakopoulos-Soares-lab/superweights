"""
Single-sequence probes for the forward pass.
Yu et al. (2024) only requires one probe — a single forward pass is enough to locate
super weights. Multiple probes are used only to verify position-invariance afterward.

All sequences are real eukaryotic coding sequences, divisible by 6 bp to satisfy
GENERator's 6-mer tokenizer.  Lengths chosen to give stable perplexity estimates:
  actb_500  → 504 bp = 84 tokens   (detection + quick ablation)
  actb_full → 1128 bp = 188 tokens (destruction test / ablation)
"""

