# Trim to exact multiples of 6 bp for GENERator's 6-mer tokenizer
# Full: 1128 bp ÷ 6 = 188 tokens  (last codon TAA = stop, total divisible by 6? check below)
# 1128 % 6 == 0 ✓   504 % 6 == 0 ✓
_ACTB_LEN = len(_ACTB_CDS)
assert _ACTB_LEN % 6 == 0, f"ACTB_CDS length {_ACTB_LEN} is not divisible by 6"

PROBES = {
    # 504 bp = 84 tokens — default for detection and quick sanity checks
    "actb_500":       _ACTB_CDS[:504],
    # Full 1128 bp = 188 tokens — use for destruction tests / ablation
    "actb_full":      _ACTB_CDS,
    # Legacy names kept for back-compat, now backed by real sequence
    "human_promoter": _ACTB_CDS[:504],
    "atg_context":    _ACTB_CDS[:504],
    # Poly-A retained as a sanity-check outlier (expect high perplexity)
    "poly_a":         "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA",
}

DEFAULT_PROBE = PROBES["actb_500"]


def get_probe(name: str = "actb_500") -> str:
    if name not in PROBES:
        raise ValueError(f"Unknown probe '{name}'. Available: {list(PROBES.keys())}")
    return PROBES[name]
